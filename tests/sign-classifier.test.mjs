function hand(letter) {
  return references[letter].map(([x, y, z]) => ({ x, y, z }));
}

function imagePoints(points) {
  return points.map(({ x, y, z }) => ({ x: .5 + x * 3, y: .5 + y * 3, z: z * 3 }));
}

test('identifies the three supported static reference signs', () => {
  for (const letter of 'ABC') {
    const world = hand(letter);
    assert.equal(classifySign(imagePoints(world), world), letter);
  }
});

test('rejects reference poses from outside of the pilot', () => {
  for (const letter of 'ENOSWY') {
    const world = hand(letter);
    assert.equal(classifySign(imagePoints(world), world), null, 'reference ' + letter);
  }
});

test('keeps classifications under 3D translation, scale, rotation, and mirroring', () => {
  for (const letter of 'ABC') {
    const world = hand(letter);
    const transformed = world.map(({ x, y, z }) => ({ x: 3 * y + 1, y: 3 * x - .5, z: z * 3 + .25 }));
    assert.equal(classifySign(imagePoints(world), transformed), letter);
  }
});

test('rejects absent, clipped, tiny or invalid landmark sets', () => {
  const world = hand('B');
  const image = imagePoints(world);
  assert.equal(classifySign(image), null);
  assert.equal(classifySign([], world), null);
  assert.equal(classifySign(image.slice(1), world), null);
  assert.equal(classifySign(image, Array(21)), null);
  assert.equal(classifySign(image, world.map(point => ({ ...point, z: Infinity }))), null);
  assert.equal(classifySign(image, world.map(() => ({ x: 0, y: 0, z: 0 }))), null);
  assert.equal(classifySign(image.map(({ x, y, z }) => ({ x: .5 + x / 70, y: .5 + y / 70, z })), world), null);
  assert.equal(classifySign(image.map((point, index) => index === 8 ? { ...point, x: .01 } : point), world), null);
});
